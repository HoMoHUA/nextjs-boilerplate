// Synthetic fixtures exercise topic-based projection, not production agent data.
import assert from "node:assert/strict";
import * as topics from "./topics";
import { getState, setState, actions } from "./store";
import { seedState, lookFor } from "./seed";
import type { Agent, OfficeState, Room } from "./types";
const base=seedState();
const native:Agent[]=["Hermes","Claude Code","Worker abc"].map((name,i)=>({id:`engine-${i}`,name,title:"runtime",persona:"",isLead:i===0,status:"idle",look:lookFor(name)}));
const room=(id:string,name:string):Room=>({...base.rooms[0],id:`tg-topic-${id}`,name,agents:native,telegram:{groupId:"-1004374108988",topicId:id,busy:false,pendingMessages:[]}});
const a=room("23","کفش ردپا"),b=room("7785","Team");
setState(()=>({...base,rooms:[a,b,base.rooms[0]],activeRoomId:a.id}));
const projection=topics as unknown as {topicActors?:(s:OfficeState)=>Agent[];visibleRooms?:(s:OfficeState)=>Room[]};
const actors=projection.topicActors?.(getState()) ?? getState().rooms[0].agents;
assert.equal(actors.length,2,"one character per topic, not one per runtime engine or worker");
assert.deepEqual(actors.map(a=>a.name),["کفش ردپا","Team"]);
assert.deepEqual(actors.map(a=>a.topicRoomId),[a.id,b.id]);
assert.equal(new Set(actors.map(a=>a.id)).size,2);
const visibility=actions as typeof actions & {setTopicVisibility:(ids:string[]|undefined)=>void};
visibility.setTopicVisibility(["7785"]);
assert.equal(getState().activeRoomId,b.id,"hiding active topic selects a visible topic");
assert.deepEqual(projection.visibleRooms!(getState()).filter(r=>r.telegram).map(r=>r.id),[b.id]);
assert.ok(projection.visibleRooms!(getState()).some(r=>!r.telegram),"independent rooms retained");
assert.equal(getState().rooms.filter(r=>r.telegram).length,2,"hiding never deletes data");
visibility.setTopicVisibility([]);
assert.equal(projection.topicActors!(getState()).length,0,"none means genuinely no topic characters");
visibility.setTopicVisibility(["23","23","999"]);
assert.deepEqual(getState().visibleTopicIds,["23"],"dedupe and scope to known topic IDs");
const oldId=projection.topicActors!(getState())[0].id;
setState(s=>({...s,rooms:[...s.rooms].reverse().map(r=>r.id===a.id?{...r,name:"ردپا مشهد"}:r)}));
assert.equal(projection.topicActors!(getState())[0].id,oldId,"identity stable across rename/reorder");
assert.equal(projection.topicActors!(getState())[0].name,"ردپا مشهد");
visibility.setTopicVisibility(undefined);
assert.equal(projection.topicActors!(getState()).length,2);
console.log("PASS one named topic character, visibility/all/none, active fallback, stable identity, independent/data retention");
